/** Сцена траектории по группе техники */
export const groupScene: Partial<Record<string, TrajectoryScene>> = {
  otrk: 'ballistic',
  airdef: 'sam',
  manpads: 'sam',
  atgm: 'atgm',
};

/** Комплексы, ракеты которых летят по квазибаллистической траектории. */
const QUASI_ITEMS = new Set(['iskander', 'atacms', 'prsm', 'lora']);
/** Зенитные комплексы без ракет: только пушки. */
const GUN_AIR_DEFENSE = new Set(['s-60', 'zsu-57-2', 'zu-23-2', 'm42', 'm163', 'gepard']);
/** Корабельные группы: если ракет нет, показываем стрельбу орудий. */
const SHIP_GROUPS = new Set(['surface', 'frigates', 'amphibious']);

/**
 * Сцена траектории для страницы техники. У зенитных пушек показывается стрельба по упреждению,
 * у кораблей без ракет вместо пуска показывается огонь орудий.
 */
export function equipmentScene(item: { id: string; group: string }, hasLaunch: boolean): TrajectoryScene | undefined {
  if (GUN_AIR_DEFENSE.has(item.id)) return 'burst';
  if (item.group === 'otrk') return QUASI_ITEMS.has(item.id) ? 'quasi' : 'ballistic';
  if (SHIP_GROUPS.has(item.group) && !hasLaunch) return 'navalfire';
  return groupScene[item.group];
}

const QUASI_BALLISTIC = new Set(['atacms-missile', '9m723', 'prsm-missile', 'pralay', 'hyunmoo-2', 'lora-missile']);
const AIRCRAFT_ROCKETS = new Set(['hydra-70', 'zuni', 'ffar', 's-5', 's-8', 's-13', 's-24', 's-25', 'sneb-68', 'crv7']);

/** Сцена траектории образца. Возвращает undefined, если подходящей анимации нет. */
export function trajectoryOf(weapon: WeaponData, categoryScene?: TrajectoryScene): TrajectoryScene | undefined {
  if (QUASI_BALLISTIC.has(weapon.id)) return 'quasi';
  if (AIRCRAFT_ROCKETS.has(weapon.id)) return 'agm';
  switch (weapon.category) {
    case 'agm': return 'agm';
    case 'arm': return 'arm';
    case 'asw': return undefined;
    default: return categoryScene;
  }
}
