/**
 * Радиолокационные средства кораблей и зенитных комплексов: тип обзора, сектор и дальность.
 * Значения приведены по открытым источникам и округлены. Если данных нет, поле не заполняется.
 */
export type SensorType = 'rotating' | 'array' | 'sector' | 'track';

export interface Sensor {
  id: string;
  name: string;
  /** Назначение одной фразой. */
  role: string;
  type: SensorType;
  /** Полуширина сектора по азимуту, градусы. 180 означает круговой обзор. */
  half: number;
  /** Направление центра сектора от носа или от оси пусковой, градусы по часовой стрелке. */
  center?: number;
  /** Число неподвижных антенных полотен (для type: 'array'). */
  faces?: number;
  /** Дальность обнаружения по открытым данным, км. */
  rangeKm?: number;
  /** Сектор по углу места [от, до], градусы. */
  elev?: [number, number];
  /** Период обзора, с. */
  period?: number;
  band?: string;
  note?: string;
}

